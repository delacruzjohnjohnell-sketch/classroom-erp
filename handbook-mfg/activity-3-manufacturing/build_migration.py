#!/usr/bin/env python3
"""Writes supabase/migrations/0063_mfg_answer_key_activity_3.sql: the Activity 3 answer-key loader (from gen.py) and the three release / open-key functions
taught about 'activity-3-manufacturing'. Run from anywhere:  python3 build_migration.py"""
import os, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", ".."))
func = subprocess.run([sys.executable, os.path.join(here, "gen.py"), "func"], capture_output=True, text=True, check=True).stdout
count = subprocess.run([sys.executable, os.path.join(here, "gen.py"), "count"], capture_output=True, text=True, check=True).stdout.strip()

header = f"""-- ============================================================
-- Classroom ERP — migration 0063 (Manufacturing ERP: the answer key for Activity 3, the team practice set)
--
-- Needs 0049 (teams), 0051/0053/0061 (answer key) and 0062 (role checks, Finance-manager release of held invoices).
--
--   mfg__load_activity_3(tenant)   Internal: posts the Activity 3 answer key (Capiz Lantern Works, February and March 2027) into a TEAM company by running
--                                  {count.split(' ', 1)[0]} steps through the real mfg_* functions, as a user who holds every role. Each step is one small JSON object
--                                  that the interpreter below turns into the same call the screen makes. (Generated by handbook-mfg/activity-3-manufacturing/gen.py.)
--   mfg_activity_release, mfg_activity_release_company, mfg_open_answer_key
--                                  Until now they accepted the first two activities. They now accept 'activity-3-manufacturing' too; the open-key function
--                                  names the company "Activity 3 answer key" and loads this key.
--
-- ROLLBACK:  drop function if exists mfg__load_activity_3(uuid);   then re-run the definitions of the three functions from 0061.
-- ============================================================

"""

patch = """

revoke execute on function mfg__load_activity_3(uuid) from public, anon, authenticated;

-- ---------- the three activities are accepted, and the right key is loaded ----------
do $do$
declare
  d text; n text;
begin
  for d in select pg_get_functiondef(p.oid) from pg_proc p join pg_namespace s on s.oid = p.pronamespace
            where s.nspname = 'public' and p.proname in ('mfg_activity_release', 'mfg_activity_release_company', 'mfg_open_answer_key') loop
    n := replace(d, 'p_activity not in (''activity-1-manufacturing'', ''activity-2-manufacturing'')', 'p_activity not in (''activity-1-manufacturing'', ''activity-2-manufacturing'', ''activity-3-manufacturing'')');
    if position('mfg_open_answer_key' in d) > 0 and position('mfg__load_activity_2' in d) > 0 then
      n := replace(n, 'case p_activity when ''activity-2-manufacturing'' then ''Activity 2 answer key'' else ''Activity 1 answer key'' end',
                      'case p_activity when ''activity-3-manufacturing'' then ''Activity 3 answer key'' when ''activity-2-manufacturing'' then ''Activity 2 answer key'' else ''Activity 1 answer key'' end');
      n := replace(n, 'if p_activity = ''activity-2-manufacturing'' then perform mfg__load_activity_2(t); else perform mfg__load_activity_1(t); end if;',
                      'if p_activity = ''activity-3-manufacturing'' then perform mfg__load_activity_3(t); elsif p_activity = ''activity-2-manufacturing'' then perform mfg__load_activity_2(t); else perform mfg__load_activity_1(t); end if;');
      if position('mfg__load_activity_3' in n) = 0 or position('Activity 3 answer key' in n) = 0 then
        raise exception 'mfg_open_answer_key did not look as expected; nothing changed.';
      end if;
    end if;
    if n = d then raise exception 'a release function did not look as expected; nothing changed.'; end if;
    execute n;
  end loop;
end $do$;

revoke execute on function mfg_activity_release(text, uuid, boolean) from public, anon;
revoke execute on function mfg_activity_release_company(text, uuid, boolean) from public, anon;
revoke execute on function mfg_open_answer_key(text) from public, anon;
grant execute on function mfg_activity_release(text, uuid, boolean) to authenticated;
grant execute on function mfg_activity_release_company(text, uuid, boolean) to authenticated;
grant execute on function mfg_open_answer_key(text) to authenticated;
"""

out = os.path.join(root, "supabase", "migrations", "0063_mfg_answer_key_activity_3.sql")
open(out, "w").write(header + func.rstrip("\n") + patch)
print("wrote", out, len(header) + len(func) + len(patch), "bytes;", count)
