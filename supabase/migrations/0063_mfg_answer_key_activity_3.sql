    when 'fgr' then
      perform mfg_post_fg_receipt(ord, (a->>'qty')::numeric, case when a->>'q' = '1' then (select id from mfg_storage_locations where tenant_id = v_t and code = 'QUARANTINE') end, null, null, (a->>'d')::date);
